<#
.SYNOPSIS
  Adds an SPDX licence identifier and copyright header to source files.

.DESCRIPTION
  Header added (comment syntax chosen per extension):
      SPDX-License-Identifier: AGPL-3.0-only
      Copyright (c) 2026 Wissam HANNA
  Handles .cs .js .css .ps1 only. XML/HTML files (.csproj, .props, .slnx, .html) are not touched (a comment can break
  an XML declaration or HTML doctype/quirks mode; add those by hand if wanted).
  Skips: bin, obj, artifacts, _parked, EXAMPLES, .git, node_modules, files already containing "SPDX-License-Identifier",
  generated files (*.g.cs, *.g.i.cs, *.AssemblyInfo.cs, files containing "<auto-generated").
  Preserves the file's BOM and line endings (CRLF or LF).

  DRY RUN BY DEFAULT: nothing is written unless -Apply is given.
  Do not run while other people or agents are editing source files.

.EXAMPLE
  pwsh tools/spdx-headers.ps1            # dry run: lists the files that would change
  pwsh tools/spdx-headers.ps1 -Apply     # writes the headers
  pwsh tools/spdx-headers.ps1 -Apply -Holder "Wissam HANNA" -Year 2026
  git diff --stat                        # review, then: dotnet build; dotnet test
#>
[CmdletBinding()]
param(
    [switch]$Apply,
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path,
    [string]$Spdx = 'AGPL-3.0-only',
    [string]$Holder = 'Wissam HANNA',
    [string]$Year = '2026'
)
$ErrorActionPreference = 'Stop'

$line1 = "SPDX-License-Identifier: $Spdx"
$line2 = "Copyright (c) $Year $Holder"
$excludeDirs = @('bin', 'obj', 'artifacts', '_parked', 'EXAMPLES', '.git', '.vs', 'node_modules', 'TestResults')
$lineStyle = @('.cs', '.js', '.ps1')      # .ps1 uses # comments
$blockStyle = @('.css')
$xmlStyle = @('.props', '.csproj', '.slnx') # only with -IncludeXml (XML declaration must stay first)

function Get-Header([string]$ext, [string]$nl) {
    switch ($ext) {
        '.cs'  { return "// $line1$nl// $line2$nl$nl" }
        '.js'  { return "// $line1$nl// $line2$nl$nl" }
        '.ps1' { return "# $line1$nl# $line2$nl$nl" }
        '.css' { return "/* $line1$nl   $line2 */$nl$nl" }
        default { return $null }
    }
}

$exts = $lineStyle + $blockStyle
$changed = 0; $skipped = 0
Get-ChildItem -Path $Root -Recurse -File | Where-Object {
    $rel = $_.FullName.Substring($Root.Length).TrimStart('\', '/')
    $parts = $rel -split '[\\/]'
    -not ($parts | Where-Object { $excludeDirs -contains $_ }) -and ($exts -contains $_.Extension.ToLowerInvariant())
} | ForEach-Object {
    $path = $_.FullName
    $ext = $_.Extension.ToLowerInvariant()
    if ($_.Name -match '\.(g|g\.i)\.cs$' -or $_.Name -match 'AssemblyInfo\.cs$' -or $_.Name -match '\.AssemblyAttributes\.cs$') { $skipped++; return }
    # Never touch this script's own header logic file twice
    $bytes = [System.IO.File]::ReadAllBytes($path)
    $bom = ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF)
    $text = [System.Text.Encoding]::UTF8.GetString($bytes, $(if ($bom) { 3 } else { 0 }), $bytes.Length - $(if ($bom) { 3 } else { 0 }))
    if ($text -match 'SPDX-License-Identifier' -or $text -match '<auto-generated') { $skipped++; return }
    $nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $header = Get-Header $ext $nl
    # PowerShell scripts: keep a leading #requires / comment-based help block valid by inserting after "#!" or "#requires" lines
    if ($ext -eq '.ps1' -and $text -match '^(#!|#requires)') {
        $firstLineEnd = $text.IndexOf($nl)
        $newText = $text.Substring(0, $firstLineEnd + $nl.Length) + $header + $text.Substring($firstLineEnd + $nl.Length)
    } else {
        $newText = $header + $text
    }
    $rel = $path.Substring($Root.Length).TrimStart('\', '/')
    if ($Apply) {
        $enc = New-Object System.Text.UTF8Encoding($bom)
        $out = $enc.GetBytes($newText)
        if ($bom) { $out = $enc.GetPreamble() + $out }
        [System.IO.File]::WriteAllBytes($path, $out)
        Write-Host "updated  $rel"
    } else {
        Write-Host "would update  $rel"
    }
    $changed++
}
Write-Host ("{0} file(s) {1}; {2} skipped (already tagged / generated)." -f $changed, $(if ($Apply) { 'updated' } else { 'would be updated (dry run, use -Apply)' }), $skipped)
